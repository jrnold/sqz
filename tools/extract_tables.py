#!/usr/bin/env python3
"""Regenerates src/text_code.rs from Synex's reader driver, FRWQ!.TRN, which isn't redistributed here.

usage: extract_tables.py FRWQ!.TRN src/text_code.rs
"""

import struct
import sys

LOOKUP = 0x3F55  # 256 entries: symbol, code length, tree pointer
TREE = 0x4355  # nodes: symbol, then pointers for a 1 bit and a 0 bit


def read_code(driver: bytes) -> dict[str, int]:
    code = {}

    def walk(ptr: int, bits: str) -> None:
        sym = driver[TREE + ptr]
        if sym:
            code[bits] = sym
            return
        one, zero = struct.unpack_from("<HH", driver, TREE + ptr + 1)
        walk(one, bits + "1")
        walk(zero, bits + "0")

    for i in range(256):
        sym, length, ptr = struct.unpack_from("<BBH", driver, LOOKUP + 4 * i)
        bits = f"{i:08b}"
        if length:
            code[bits[:length]] = sym
        else:
            walk(ptr, bits)
    return code


def main() -> None:
    code = read_code(open(sys.argv[1], "rb").read())
    items = sorted(code.items(), key=lambda kv: (len(kv[0]), kv[0]))
    assert sum(2 ** -len(k) for k in code) == 1, "not a complete prefix code"
    rows = "".join(f"    ({len(k)}, 0b{k}, 0x{v:02x}),\n" for k, v in items)
    with open(sys.argv[2], "w") as out:
        out.write("//! Static SQZ! text code: (bit length, code, symbol). See `FORMAT.md`.\n")
        out.write("//! Generated by `tools/extract_tables.py`.\n")
        out.write(f"pub(crate) const TEXT_CODE: &[(u8, u16, u8)] = &[\n{rows}];\n")


if __name__ == "__main__":
    main()
